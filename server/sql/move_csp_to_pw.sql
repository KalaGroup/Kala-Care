    (SELECT COUNT(*) FROM #move)                                               AS followup_rows_to_move,
    (SELECT COUNT(DISTINCT customer_id) FROM #move)                             AS customers_with_rows_to_move,
    (SELECT COUNT(*) FROM #membership WHERE which_list = 'asset')               AS drive_memberships_to_remove,
    (SELECT COUNT(DISTINCT campaign_id) FROM #rebuilt)                          AS drives_to_update;


/* ---------------------------------------------------------------------------
   Step 6 : THE MOVE  (runs automatically -- no flag to set)
   ------------------------------------------------------------------------- */
IF EXISTS (SELECT 1 FROM #move) OR EXISTS (SELECT 1 FROM #rebuilt)
BEGIN
    BEGIN TRANSACTION;

    -- 6a. audit every row before it is touched (makes this reversible)
    INSERT INTO dbo.followup_move_log
        (moved_by, direction, source_table, source_row_id, customer_id,
         instance_id, source_campaign_id, source_campaign_name, target_campaign_id, row_json)
    SELECT
        SUSER_SNAME(), 'CSP->PW', 'followups', m.id, m.customer_id,
        m.resolved_instance_id, m.campaign_id, m.drive_name, NULL,
        (SELECT m2.* FROM #move m2 WHERE m2.id = m.id FOR JSON PATH, WITHOUT_ARRAY_WRAPPER)
    FROM #move m;

    -- 6b. write them as Post Warranty rows (campaign_id = NULL)
    --     followup_date and created_at are preserved: created_at is what the
    --     employee-performance reports bucket by, so restamping it would move
    --     the work to today.
    INSERT INTO non_followups
        (customer_id, customer_instance_id, campaign_id, user_id, user_name,
         followup_date, followup_by, followup_remark, status, remark_type,
         service, followup_flag, next_followup_date,
         quotation_sent, quotation_no, quotation_value,
         activity_id, rr_id, created_at, updated_at)
    SELECT
        m.customer_id,
        ISNULL(m.customer_instance_id, m.resolved_instance_id),
        NULL,                                                   -- <= this is what makes it Post Warranty
        m.user_id,
        ISNULL(NULLIF(LTRIM(RTRIM(m.user_name)), N''), m.user_id),
        m.followup_date,
        ISNULL(NULLIF(LTRIM(RTRIM(m.followup_by)), N''), N'call'),      -- NOT NULL in non_followups
        m.followup_remark,
        ISNULL(NULLIF(LTRIM(RTRIM(m.status)), N''), N'pending'),        -- NOT NULL in non_followups
        N'other',                                                       -- remark_type, NOT NULL
        m.drive_service,                                                -- keeps the product on the PW row
        m.followup_flag,
        m.next_followup_date,
        ISNULL(m.quotation_sent, 0),
        m.quotation_no,
        m.quotation_value,
        m.activity_id,
        m.rr_id,
        CAST(m.created_at AS DATETIME),                                 -- drops the meaningless +00:00 offset
        GETDATE()
    FROM #move m;

    -- 6c. remove the originals
    DELETE f
    FROM followups f
    JOIN #move m ON m.id = f.id;

    -- 6d. take the instances OFF the CSP drives' membership lists, so the drive
    --     columns stop showing them. Runs for every listed instance, including
    --     the ones that had no follow-up to move.
    --     Bumping updated_at also drops the Non-Drive page's 60s cached index
    --     (_non_campaign_signature hashes active campaigns' updated_at).
    UPDATE cp
    SET cp.asset_numbers       = r.new_assets,
        cp.admin_asset_numbers = r.new_admin,
        cp.updated_at          = GETDATE()
    FROM campaigns cp
    JOIN #rebuilt r ON r.campaign_id = cp.id;

    -- 6e. drives that only lost follow-ups (not membership) still need the bump
    UPDATE cp
    SET cp.updated_at = GETDATE()
    FROM campaigns cp
    WHERE cp.id IN (SELECT DISTINCT campaign_id FROM #move)
      AND NOT EXISTS (SELECT 1 FROM #rebuilt r WHERE r.campaign_id = cp.id);

    COMMIT TRANSACTION;
    PRINT 'CSP -> PW move committed (follow-ups moved + drive membership cleaned).';
END
ELSE
    PRINT 'Nothing to move and nothing to remove.';


