                THEN LEFT(LTRIM(RTRIM(v.value)), LEN(LTRIM(RTRIM(v.value))) - 2)
                ELSE LTRIM(RTRIM(v.value)) END AS norm_v
    FROM OPENJSON(CASE WHEN ISJSON(cp.admin_asset_numbers) = 1 THEN cp.admin_asset_numbers ELSE N'[]' END) v
) x
WHERE EXISTS (SELECT 1 FROM #ids i WHERE i.norm_id = x.norm_v);


/* ---------------------------------------------------------------------------
   Step 4c : rebuild those drives' lists with the instances taken out.
             Only drives that actually list one of them are touched, so no
             other drive's JSON gets reformatted.
             The ISJSON guard sits INSIDE the OPENJSON argument on purpose:
             OPENJSON runs before a WHERE clause could filter a bad value out.
   ------------------------------------------------------------------------- */
SELECT
    cp.id   AS campaign_id,
    cp.name AS drive_name,
    a.new_assets,
    b.new_admin
INTO #rebuilt
FROM campaigns cp
JOIN #csp_drives d ON d.id = cp.id
OUTER APPLY (
    -- CAST to NVARCHAR(MAX) is required: STRING_AGG returns nvarchar(4000) when
    -- fed a non-MAX expression and then ERRORS at 8000 bytes, which a drive with
    -- a few hundred assets exceeds.
    SELECT N'[' + ISNULL(STRING_AGG(CAST(N'"' + v.value + N'"' AS NVARCHAR(MAX)), N','), N'') + N']' AS new_assets
    FROM OPENJSON(CASE WHEN ISJSON(cp.asset_numbers) = 1 THEN cp.asset_numbers ELSE N'[]' END) v
    WHERE LTRIM(RTRIM(v.value)) <> N''
      AND NOT EXISTS (SELECT 1 FROM #ids i WHERE i.norm_id = CASE WHEN RIGHT(LTRIM(RTRIM(v.value)), 2) = N'.0'
                THEN LEFT(LTRIM(RTRIM(v.value)), LEN(LTRIM(RTRIM(v.value))) - 2)
                ELSE LTRIM(RTRIM(v.value)) END)
) a
OUTER APPLY (
    SELECT N'[' + ISNULL(STRING_AGG(CAST(N'"' + v.value + N'"' AS NVARCHAR(MAX)), N','), N'') + N']' AS new_admin
    FROM OPENJSON(CASE WHEN ISJSON(cp.admin_asset_numbers) = 1 THEN cp.admin_asset_numbers ELSE N'[]' END) v
    WHERE LTRIM(RTRIM(v.value)) <> N''
      AND NOT EXISTS (SELECT 1 FROM #ids i WHERE i.norm_id = CASE WHEN RIGHT(LTRIM(RTRIM(v.value)), 2) = N'.0'
                THEN LEFT(LTRIM(RTRIM(v.value)), LEN(LTRIM(RTRIM(v.value))) - 2)
                ELSE LTRIM(RTRIM(v.value)) END)
) b
WHERE EXISTS (SELECT 1 FROM #membership mb WHERE mb.campaign_id = cp.id);


